# ------------------------------------------------------------------
# Convenience function
# ------------------------------------------------------------------

def generate_and_save_test_vectors(
    workspace: Optional[str] = None,
    grid_arrays: Optional[dict] = None,
) -> tuple[Path, Path]:
    """
    Convenience: generate and save a complete test vector suite.

    Parameters
    ----------
    workspace : str, optional
        Output directory for test vector files.
    grid_arrays : dict, optional
        Grid arrays for wave generation (x, y, z, t). If not provided,
        a default grid is used.

    Returns
    -------
    tuple of (json_path, rust_path)
    """
    from xpock.cli import generate_wave_event

    if grid_arrays is None:
        grid_arrays = {
            "x": np.linspace(-5, 5, 64),
            "y": np.linspace(-5, 5, 64),
            "z": np.array([0.0]),
            "t": np.linspace(-5, 5, 64),
        }

    # Generate sample wave events for capacity analysis
    wave_events = []
    for params in [
        {
            "temporal_shape": "gaussian",
            "temporal_duration": 1.0,
            "spatial_mode": "gaussian",
            "spatial_waist": 1.0,
            "polarization_state": "linear",
        },
        {
            "temporal_shape": "sech",
            "temporal_duration": 1.0,
            "spatial_mode": "laguerre_gaussian",
            "spatial_l": 1,
            "spatial_waist": 1.0,
            "polarization_state": "circular",
        },
    ]:
        ev = generate_wave_event(params, grid_arrays)
        wave_events.append(ev)

    generator = TestVectorGenerator(workspace=workspace)
    test_set = generator.generate_full_suite(
        carrier_scenarios=default_carrier_scenarios(),
        impairment_scenarios=default_impairment_scenarios(),
        snr_values=default_snr_values(),
        bandwidth_values=default_bandwidth_values(),
        wave_events=wave_events,
        scheme_configs=default_scheme_configs(),
        grid_arrays=grid_arrays,
    )

    return generator.save_all(test_set)
