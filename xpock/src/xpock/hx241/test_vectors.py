"""
XPOCK — HX-241 Test Vector Generation

Generates Rust-compatible test vectors from XPOCK's physically-based carrier
models, channel capacity analysis, and impairment models. These vectors can be
consumed directly by hx-sim's impairment engine, transport layer tests, and
adversarial test suites.

Output formats:
- JSON: Human-readable, easily parsed by Rust's serde
- Rust source: Embedded test data as Rust literals for compile-time inclusion

HX-241 architectural compliance: test vectors describe physical carrier
behavior only. HX-241 protocol logic is not modified or dependent on these
vectors. They are inputs to hx-sim's NetworkImpairment and conformance tests.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Optional, Dict, Any, List
from pathlib import Path
import json
import numpy as np

from xpock.hx241.carrier import (
    CarrierWaveConfig,
    CarrierChannelModel,
    CarrierMedium,
    CarrierWaveModeler,
)
from xpock.hx241.impairment import (
    ImpairmentProfile,
    ImpairmentModeler,
    impairment_to_hx_sim_dict,
)
from xpock.hx241.channel import ChannelCapacityAnalyzer
from xpock.core import WaveEvent, WaveField
from xpock.cli import generate_wave_event


@dataclass
class TestVectorSet:
    """A collection of test vectors for HX-241 Rust consumption."""

    name: str
    description: str
    carrier_models: List[Dict[str, Any]] = field(default_factory=list)
    impairment_profiles: List[Dict[str, Any]] = field(default_factory=list)
    capacity_results: List[Dict[str, Any]] = field(default_factory=list)
    modulation_constellations: List[Dict[str, Any]] = field(default_factory=list)
    metadata: Dict[str, Any] = field(default_factory=dict)

    def to_json(self) -> str:
        """Serialize to JSON for Rust serde consumption."""
        return json.dumps(
            {
                "name": self.name,
                "description": self.description,
                "carrier_models": self.carrier_models,
                "impairment_profiles": self.impairment_profiles,
                "capacity_results": self.capacity_results,
                "modulation_constellations": self.modulation_constellations,
                "metadata": self.metadata,
            },
            indent=2,
            default=str,
        )

    def to_rust_source(self, var_name: str = "XPOCK_TEST_VECTORS") -> str:
        """Generate Rust source file with embedded test vectors.

        Produces a Rust module with the test vectors as a static string
        that can be parsed at runtime with serde_json.
        """
        json_str = self.to_json()
        # Escape for Rust string literal
        escaped = json_str.replace("\\", "\\\\").replace('"', '\\"')
        rust = f"""// Auto-generated by XPOCK test vector generator
// Source: {self.name}
// Description: {self.description}
// Do not edit manually

#[allow(dead_code)]
pub const {var_name}: &str = r#"{escaped}"#;

#[allow(dead_code)]
pub fn {var_name.lower()}_json() -> &'static str {{
    {var_name}
}}
"""
        return rust


class TestVectorGenerator:
    """
    Generates HX-241 test vectors from XPOCK models.

    Produces vectors for:
    1. Carrier channel models (path loss, SNR, delay spread, coherence bandwidth)
    2. Impairment profiles (hx-sim NetworkImpairment-compatible)
    3. Channel capacity results (Shannon capacity, distinguishable states)
    4. Modulation constellations (wave structure → bit mappings)
    """

    def __init__(self, workspace: Optional[str] = None):
        self.workspace = Path(workspace) if workspace else Path("./xpock_hx241_vectors")
        self.workspace.mkdir(parents=True, exist_ok=True)
        self._carrier_modeler: Optional[CarrierWaveModeler] = None
        self._impairment_modeler: Optional[ImpairmentModeler] = None
        self._capacity_analyzer: Optional[ChannelCapacityAnalyzer] = None

    def _get_carrier_modeler(self) -> CarrierWaveModeler:
        if self._carrier_modeler is None:
            self._carrier_modeler = CarrierWaveModeler(
                workspace=str(self.workspace / "carrier")
            )
        return self._carrier_modeler

    def _get_impairment_modeler(self) -> ImpairmentModeler:
        if self._impairment_modeler is None:
            self._impairment_modeler = ImpairmentModeler(
                workspace=str(self.workspace / "impairment")
            )
        return self._impairment_modeler

    def _get_capacity_analyzer(self) -> ChannelCapacityAnalyzer:
        if self._capacity_analyzer is None:
            self._capacity_analyzer = ChannelCapacityAnalyzer(
                workspace=str(self.workspace / "capacity")
            )
        return self._capacity_analyzer

    # ------------------------------------------------------------------
    # Carrier model test vectors
    # ----------------------------------------------------------------------

    def generate_carrier_vectors(
        self,
        scenarios: List[Dict[str, Any]],
    ) -> List[Dict[str, Any]]:
        """
        Generate carrier channel model test vectors.

        Each scenario dict should contain keys for CarrierWaveConfig:
        medium, frequency_hz, distance_m, transmit_power_w, plus
        medium-specific kwargs.

        Returns list of dicts with carrier model results plus hx-sim
        compatible impairment parameters.
        """
        modeler = self._get_carrier_modeler()
        vectors: List[Dict[str, Any]] = []

        for i, scenario in enumerate(scenarios):
            config = CarrierWaveConfig(
                medium=CarrierMedium(scenario["medium"]),
                frequency_hz=scenario["frequency_hz"],
                distance_m=scenario["distance_m"],
                transmit_power_w=scenario.get("transmit_power_w", 1.0),
                medium_specific=scenario.get("medium_specific", {}),
            )
            channel = modeler.model_carrier(config)

            vector = {
                "id": f"carrier_{i:04d}",
                "medium": config.medium.value,
                "frequency_hz": config.frequency_hz,
                "wavelength_m": config.wavelength_m,
                "distance_m": config.distance_m,
                "transmit_power_w": config.transmit_power_w,
                "path_loss_db": channel.path_loss_db,
                "snr_db": channel.snr_db,
                "delay_spread_s": channel.delay_spread_s,
                "coherence_bandwidth_hz": channel.coherence_bandwidth_hz,
                "doppler_spread_hz": channel.doppler_spread_hz,
                "capacity_bps": channel.capacity_bps,
                "impairment_params": channel.impairment_params,
                "medium_notes": channel.medium_notes,
            }
            vectors.append(vector)

        return vectors

    # ------------------------------------------------------------------
    # Impairment profile test vectors
    # ----------------------------------------------------------------------

    def generate_impairment_vectors(
        self,
        scenarios: List[Dict[str, Any]],
    ) -> List[Dict[str, Any]]:
        """
        Generate impairment profile test vectors for hx-sim.

        Each scenario dict contains carrier model parameters plus
        medium-specific kwargs. Returns hx-sim NetworkImpairment-compatible
        parameters.
        """
        modeler = self._get_impairment_modeler()
        vectors: List[Dict[str, Any]] = []

        for i, scenario in enumerate(scenarios):
            profile = modeler.generate_impairment_scenario(
                medium=CarrierMedium(scenario["medium"]),
                distance_m=scenario["distance_m"],
                frequency_hz=scenario["frequency_hz"],
                transmit_power_w=scenario.get("transmit_power_w", 1.0),
                **scenario.get("medium_specific", {}),
            )

            hx_sim_params = impairment_to_hx_sim_dict(profile)

            vector = {
                "id": f"impairment_{i:04d}",
                "medium": profile.medium,
                "model": profile.model.value,
                "path_loss_db": profile.path_loss_db,
                "snr_db": profile.snr_db,
                "delay_spread_s": profile.delay_spread_s,
                "coherence_bandwidth_hz": profile.coherence_bandwidth_hz,
                "doppler_spread_hz": profile.doppler_spread_hz,
                "hx_sim_impairment": hx_sim_params,
                "notes": profile.notes,
            }
            vectors.append(vector)

        return vectors

    # ------------------------------------------------------------------
    # Channel capacity test vectors
    # ----------------------------------------------------------------------

    def generate_capacity_vectors(
        self,
        snr_values: List[float],
        bandwidth_values: List[float],
        wave_events: List[WaveEvent],
    ) -> List[Dict[str, Any]]:
        """
        Generate channel capacity test vectors across SNR and bandwidth
        combinations.

        Returns list of capacity analysis results for each combination.
        """
        analyzer = self._get_capacity_analyzer()
        vectors: List[Dict[str, Any]] = []

        for snr in snr_values:
            for bw in bandwidth_values:
                result = analyzer.analyze_capacity(
                    snr_db=snr,
                    bandwidth_hz=bw,
                    wave_events=wave_events,
                    error_correction_overhead=0.25,
                )
                vector = result.to_dict()
                vector["id"] = f"capacity_{snr:06.1f}db_{int(bw)}hz"
                vectors.append(vector)

        return vectors

    # ------------------------------------------------------------------
    # Modulation constellation test vectors
    # ----------------------------------------------------------------------

    def generate_constellation_vectors(
        self,
        scheme_configs: List[Dict[str, Any]],
        grid_arrays: dict,
    ) -> List[Dict[str, Any]]:
        """
        Generate modulation constellation test vectors.

        Each scheme config defines modulation dimensions and states.
        Returns constellation points with bit assignments and wave
        structure parameters.
        """
        from xpock.hx241.modulation import (
            ModulationScheme,
            ModulationDimension,
            WaveModulator,
            create_default_scheme,
        )
        from xpock.properties import PulseShape, PolarizationState

        vectors: List[Dict[str, Any]] = []

        for i, config in enumerate(scheme_configs):
            scheme = ModulationScheme()

            # Parse dimensions from config
            dim_map = {
                "temporal_shape": ModulationDimension.TEMPORAL_SHAPE,
                "oam_charge": ModulationDimension.OAM_CHARGE,
                "polarization_state": ModulationDimension.POLARIZATION_STATE,
                "temporal_duration": ModulationDimension.TEMPORAL_DURATION,
                "beam_waist": ModulationDimension.BEAM_WAIST,
                "carrier_frequency": ModulationDimension.CARRIER_FREQUENCY,
            }

            for dim_name, states in config.get("dimensions", {}).items():
                dim = dim_map.get(dim_name)
                if dim is None:
                    continue
                scheme.add_dimension(dim, states)

            modulator = WaveModulator(scheme=scheme, grid_arrays=grid_arrays)

            # Generate all constellation points
            constellation = []
            for idx in range(modulator.constellation_size()):
                mod_result = modulator.modulate_bits("0" * scheme.capacity_bits(),
                                                     symbol_index=idx)
                constellation.append({
                    "index": idx,
                    "bit_assignment": format(idx, f"0{scheme.capacity_bits()}b"),
                    "dimension_assignments": {
                        k.value: (v.value if hasattr(v, 'value') else str(v))
                        for k, v in mod_result.dimension_assignments.items()
                    },
                    "field_shape": mod_result.event.field.shape,
                    "total_power": mod_result.event.field.total_power,
                    "duration": mod_result.event.field.duration,
                })

            vectors.append({
                "id": f"constellation_{i:04d}",
                "scheme_name": config.get("name", f"scheme_{i}"),
                "capacity_bits": scheme.capacity_bits(),
                "num_states": scheme.num_states(),
                "enabled_dimensions": [
                    d.value for d in scheme.enabled_dimensions
                ],
                "constellation": constellation,
            })

        return vectors

    # ------------------------------------------------------------------
    # Complete test vector suite
    # ----------------------------------------------------------------------

    def generate_full_suite(
        self,
        carrier_scenarios: List[Dict[str, Any]],
        impairment_scenarios: List[Dict[str, Any]],
        snr_values: List[float],
        bandwidth_values: List[float],
        wave_events: List[WaveEvent],
        scheme_configs: List[Dict[str, Any]],
        grid_arrays: dict,
    ) -> TestVectorSet:
        """Generate a complete test vector suite covering all domains."""
        carrier_models = self.generate_carrier_vectors(carrier_scenarios)
        impairment_profiles = self.generate_impairment_vectors(impairment_scenarios)
        capacity_results = self.generate_capacity_vectors(
            snr_values, bandwidth_values, wave_events
        )
        modulation_constellations = self.generate_constellation_vectors(
            scheme_configs, grid_arrays
        )

        return TestVectorSet(
            name="xpock_hx241_full_suite",
            description=(
                "Complete test vector suite for HX-241 carrier modeling, "
                "channel capacity analysis, impairment modeling, and "
                "wave-structure modulation. Generated by XPOCK."
            ),
            carrier_models=carrier_models,
            impairment_profiles=impairment_profiles,
            capacity_results=capacity_results,
            modulation_constellations=modulation_constellations,
            metadata={
                "n_carrier_models": len(carrier_models),
                "n_impairment_profiles": len(impairment_profiles),
                "n_capacity_results": len(capacity_results),
                "n_constellations": len(modulation_constellations),
                "generated_by": "xpock.hx241.test_vectors",
            },
        )

    # ------------------------------------------------------------------
    # File output
    # ----------------------------------------------------------------------

    def save_json(
        self,
        test_set: TestVectorSet,
        filename: str = "xpock_hx241_test_vectors.json",
    ) -> Path:
        """Save test vectors as JSON file."""
        path = self.workspace / filename
        path.write_text(test_set.to_json(), encoding="utf-8")
        return path

    def save_rust(
        self,
        test_set: TestVectorSet,
        filename: str = "xpock_test_vectors.rs",
        var_name: str = "XPOCK_TEST_VECTORS",
    ) -> Path:
        """Save test vectors as Rust source file."""
        path = self.workspace / filename
        path.write_text(test_set.to_rust_source(var_name), encoding="utf-8")
        return path

    def save_all(
        self,
        test_set: TestVectorSet,
        json_filename: str = "xpock_hx241_test_vectors.json",
        rust_filename: str = "xpock_test_vectors.rs",
        rust_var_name: str = "XPOCK_TEST_VECTORS",
    ) -> tuple[Path, Path]:
        """Save test vectors as both JSON and Rust source."""
        json_path = self.save_json(test_set, json_filename)
        rust_path = self.save_rust(test_set, rust_filename, rust_var_name)
        return json_path, rust_path


